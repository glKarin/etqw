typedef struct VKEnumName_s
{
    int value;
    const char *name;
} VKEnumName_t;
//typedef intptr_t VKEnumNameValueWrap_t;
typedef VKEnumName_t VKEnumNameValueWrap_t;

#define VKENUM_TO_NAME_ITEM(prefix, suffix) { prefix##suffix, #suffix }
#define VKBIT_TO_NAME_ITEM(prefix, suffix) { prefix##suffix##_BIT, #suffix }
#define VKBIT_TO_NAME_ITEM2(prefix, suffix, ext) { prefix##suffix##_BIT_##ext, #suffix }
#define VKBIT_TO_NAME_ITEM_KHR(prefix, suffix) VKBIT_TO_NAME_ITEM2(prefix, suffix, KHR)
#define VKBIT_TO_NAME_ITEM_EXT(prefix, suffix) VKBIT_TO_NAME_ITEM2(prefix, suffix, EXT)
#define VKBIT_TO_NAME_ITEM_NV(prefix, suffix) VKBIT_TO_NAME_ITEM2(prefix, suffix, NV)
#define VKBIT_TO_NAME_ITEM_AND(prefix, suffix) VKBIT_TO_NAME_ITEM2(prefix, suffix, AMD)


#define VKENUM_TO_NAME_FUNC(enumType, ...) \
    VKENUM_TO_NAME_FUNC_PROTO(enumType) { \
        const VKEnumNameValueWrap_t arr[] = { \
            __VA_ARGS__ }; \
        int length = sizeof(arr) / sizeof(arr[0]); \
        for(int i = 0; i < length; i++) { \
            if(value == (enumType)arr[i].value) \
                return (const char *)arr[i].name; \
        } \
        return NULL; \
    }

static /*thread_local*/ char vkbit_to_name_func_buf[1024];
#define VKBIT_TO_NAME_FUNC(enumType, ...) \
        VKENUMBIT_TO_NAME_FUNC_PROTO(enumType) { \
        char *buf = vkbit_to_name_func_buf; \
        buf[0] = '\0'; \
        const VKEnumNameValueWrap_t arr[] = { \
            __VA_ARGS__ }; \
        int length = sizeof(arr) / sizeof(arr[0]); \
        for(int i = 0; i < length; i++) { \
            if(value & (enumType)arr[i].value) { \
                if(buf[0]) \
                    strcat(buf, "|"); \
                strcat(buf, (const char *)arr[i].name); \
            } \
        } \
        return buf; \
    }

