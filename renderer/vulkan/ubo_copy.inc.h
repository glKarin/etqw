
#define UBOPTR_TEMP(stage) void *ptr = vk_backend.currentProgram->ubo_##stage
#define UBO_TYPEDEF(stage, T) typedef UBO_DEFINE(stage, T) Type_t

#define UBOX_TRANSFORM_DECLARATION(stage, T) UBOX_TRANSFORM_DEFINE(stage, T) { \
	ASSERT_PROGRAM; \
	UBOPTR_TEMP(stage); \
	UBO_TYPEDEF(stage, T);
#define UBO0_TRANSFORM_DECLARATION(T) UBOX_TRANSFORM_DECLARATION(vertex, T)
#define UBO1_TRANSFORM_DECLARATION(T) UBOX_TRANSFORM_DECLARATION(fragment, T)
#define END_UBO_TRANSFORM }


#define SHADER_UBO_PARM_OFFSET(name) offsetof(Type_t, name)
#define SHADER_UBO_PARM_OFFSET_N(name, n) offsetof(Type_t, name##n)

#define UBO_COPY_GLOBAL_TO_SHADER(name) R_VK_TransformUniform(SHADER_UBO_PARM_OFFSET(name), VKGLOBAL_PARM_OFFSET(name), ptr, sizeof(globalUBO.name))
#define UBO_COPY_GLOBAL_TO_SHADER_N(name, n) R_VK_TransformUniform(SHADER_UBO_PARM_OFFSET_N(name, n), VKGLOBAL_PARMS_OFFSET(name, n), ptr, sizeof(globalUBO.name[n]))

#define UBO_COPY_GLOBAL_TO_SHADER_FLOAT(name) R_VK_TransformUniform1f(SHADER_UBO_PARM_OFFSET(name), VKGLOBAL_PARM_OFFSET(name), ptr)
#define UBO_COPY_GLOBAL_TO_SHADER_VEC4(name) R_VK_TransformUniform4f(SHADER_UBO_PARM_OFFSET(name), VKGLOBAL_PARM_OFFSET(name), ptr)
#define UBO_COPY_GLOBAL_TO_SHADER_MAT4(name) R_VK_TransformUniformMatrix4f(SHADER_UBO_PARM_OFFSET(name), VKGLOBAL_PARM_OFFSET(name), ptr)
#define UBO_COPY_GLOBAL_TO_SHADER_NMAT4(name) UBO_COPY_GLOBAL_TO_SHADER(name)
#define UBO_COPY_GLOBAL_TO_SHADER_INT_N(name, n) R_VK_TransformUniform1i(SHADER_UBO_PARM_OFFSET_N(name, n), VKGLOBAL_PARMS_OFFSET(name, n), ptr)
#define UBO_COPY_GLOBAL_TO_SHADER_VEC4_N(name, n) R_VK_TransformUniform4f(SHADER_UBO_PARM_OFFSET_N(name, n), VKGLOBAL_PARMS_OFFSET(name, n), ptr)


